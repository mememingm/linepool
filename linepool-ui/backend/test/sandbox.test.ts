import assert from 'node:assert/strict';
import {test} from 'node:test';
import {randomUUID} from 'node:crypto';
import type {Response} from 'express';
import {Sandbox} from '../src/sandbox.js';
import {ApiFailure} from '../src/http.js';
const code=(expected:string)=>(error:unknown)=>error instanceof ApiFailure&&(error.getResponse() as {error:{code:string}}).error.code===expected;
import {Environment} from '../src/environment.js';
import {Ordering} from '../src/ordering.js';
import {MockReceivingProvider} from '../src/providers/mock-receiving-provider.js';
import {ReceivingSync} from '../src/providers/receiving-sync.js';
import {isolatedDatabase} from './isolated-database.js';

test('local sandbox credit, pending outcomes, inbound dedupe, isolation and expiry use real transactions',async t=>{
 const f=await isolatedDatabase();t.after(()=>f.close());
 const response={cookie(){return this;},clearCookie(){return this;}} as unknown as Response;
 const a=await f.auth.register({email:`a-${randomUUID()}@example.invalid`,password:'sandbox-test-only-2026',displayName:'A'},response);
 const b=await f.auth.register({email:`b-${randomUUID()}@example.invalid`,password:'sandbox-test-only-2026',displayName:'B'},response);
 const provider=new MockReceivingProvider(),receiving=new ReceivingSync(f.db,provider);
 const enabled={values:{...f.environment.values,LOCAL_SANDBOX:true}} as Environment;
 const sandbox=new Sandbox(f.db,enabled,receiving),disabled=new Sandbox(f.db,f.environment,receiving);
 await assert.rejects(disabled.credit(a.id),code('NOT_FOUND'));
 await Promise.all([sandbox.credit(a.id),sandbox.credit(a.id),sandbox.credit(a.id)]);
 let points=await f.workspace.points(a.id,{page:1,pageSize:100});assert.equal(points.data.balance,100);assert.equal(points.data.entries.length,1);
 const ordering=new Ordering(f.db,f.workspace,provider,enabled);
 const intent={region:'us' as const,service:'Telegram' as const,plan:'week' as const,quantity:1,idempotencyKey:randomUUID()};
 const [first,replay]=await Promise.all([ordering.create(a.id,intent),ordering.create(a.id,intent)]);
 assert.equal(first.id,replay.id);assert.equal(first.status,'PROCESSING');assert.equal(first.numbers.length,0);
 await assert.rejects(sandbox.fulfill(b.id,{orderId:first.id,outcome:'SUCCESS'}),code('ORDER_NOT_FOUND'));
 assert.equal((await sandbox.fulfill(a.id,{orderId:first.id,outcome:'UNKNOWN'})).status,'UNCERTAIN');
 assert.equal((await sandbox.fulfill(a.id,{orderId:first.id,outcome:'SUCCESS'})).status,'SUCCEEDED');
 assert.equal((await sandbox.fulfill(a.id,{orderId:first.id,outcome:'SUCCESS'})).changed,false);
 await assert.rejects(sandbox.fulfill(a.id,{orderId:first.id,outcome:'FAILED'}),code('MOCK_TERMINAL'));
 const completed=await f.workspace.orderDetail(a.id,first.id),number=completed.numbers[0]!;assert.equal(completed.numbers.length,1);
 const message={id:randomUUID(),numberId:number.id,outcome:'SUCCESS' as const};
 const delivery=await Promise.all([sandbox.inbound(a.id,message),sandbox.inbound(a.id,message)]);
 assert.deepEqual(delivery.map(r=>r.status).sort(),['DUPLICATE','IMPORTED']);
 assert.equal((await f.workspace.inbox(a.id,{page:1,pageSize:100,search:''})).data.length,1);
 await assert.rejects(sandbox.inbound(b.id,message),code('IDEMPOTENCY_CONFLICT'));
 await assert.rejects(sandbox.inbound(b.id,{...message,id:randomUUID()}),code('PROVIDER_ALLOCATION_INACTIVE'));
 const unknown={id:randomUUID(),numberId:number.id,outcome:'UNKNOWN' as const};
 assert.equal((await sandbox.inbound(a.id,unknown)).status,'UNCERTAIN');
 assert.equal((await f.workspace.inbox(a.id,{page:1,pageSize:100,search:''})).data.length,1);
 assert.equal((await sandbox.inbound(a.id,{...unknown,resolve:true})).status,'IMPORTED');
 assert.equal((await sandbox.inbound(a.id,{...unknown,resolve:true})).status,'DUPLICATE');
 const failed={id:randomUUID(),numberId:number.id,outcome:'FAILED' as const};assert.equal((await sandbox.inbound(a.id,failed)).status,'FAILED');
 await assert.rejects(sandbox.inbound(a.id,{...failed,outcome:'SUCCESS'}),code('IDEMPOTENCY_CONFLICT'));
 const failedOrder=await ordering.create(a.id,{...intent,idempotencyKey:randomUUID()});
 await sandbox.fulfill(a.id,{orderId:failedOrder.id,outcome:'FAILED'});await sandbox.fulfill(a.id,{orderId:failedOrder.id,outcome:'FAILED'});
 points=await f.workspace.points(a.id,{page:1,pageSize:100});assert.equal(points.data.balance,100-first.totalPoints);
 assert.equal(points.data.entries.filter(e=>e.type==='ADJUSTMENT').length,1);
 assert.equal(points.data.entries.reduce((s,e)=>s+e.delta,0),points.data.balance);
 assert.equal((await f.workspace.inbox(b.id,{page:1,pageSize:100,search:''})).data.length,0);
 // Force only this isolated allocation to its exact expiry boundary; no live DB is used.
 await f.client.query("UPDATE phone_numbers SET assigned_at=now()-interval '8 days',expires_at=now() WHERE id=$1",[number.id]);
 await assert.rejects(sandbox.inbound(a.id,{...message,id:randomUUID()}),code('PROVIDER_ALLOCATION_INACTIVE'));
});
